<p>
  Nairobi has always moved fast. The city's matatu network — over 100,000 vehicles serving 
  millions of daily riders — is one of the most responsive, adaptive transit systems on the 
  continent. It evolved without a master plan, shaped entirely by demand, competition, and 
  the ingenuity of the operators running it.
</p>

<p>
  But fast doesn't always mean efficient. And adaptive doesn't always mean data-driven.
</p>

<p>
  Over the past year, we've been quietly collecting GPS telemetry across 340 tracked vehicles 
  spanning twelve partner saccos. What follows is what that data actually shows — not what 
  we expected to find, but what the numbers say.
</p>

<h2>Finding 1: Peak Congestion Is More Predictable Than Operators Think</h2>

<p>
  Conventional wisdom in the matatu industry treats traffic as random — an external condition 
  that drivers navigate by feel. Our data tells a different story. Congestion on Nairobi's 
  major commuter corridors follows patterns accurate enough to model with high confidence 
  several hours in advance.
</p>

<p>
  Thika Road northbound between 5:30pm and 7:15pm on weekdays adds an average of 34 minutes 
  to trip duration compared to the same run at midday. That number is consistent to within 
  six minutes across 90% of the days we sampled. It's not random. It's predictable — and 
  predictable congestion can be planned around.
</p>

<h2>Finding 2: Empty Return Trips Are the Single Biggest Efficiency Gap</h2>

<p>
  We tracked vehicle utilisation across the full operating day for a subset of 80 vehicles. 
  The result that stood out most starkly: the average vehicle runs its return leg at 
  approximately 42% of its inbound passenger load.
</p>

<p>
  This isn't purely a demand problem. Significant portions of the empty mileage occur on 
  routes where demand exists on the return corridor — it just hasn't been matched to supply 
  because operators have no visibility into where that demand is concentrated. A demand 
  heatmap updated in real time would, in theory, allow drivers to make different decisions 
  about staging, route deviation, and pickup points.
</p>

<blockquote>
  In aggregate, the vehicles we track cover an estimated 18% of their total daily kilometres 
  with zero or near-zero passenger load. That's not a rounding error — it's a structural 
  inefficiency hiding in plain sight.
</blockquote>

<h2>Finding 3: Arrival Time Variance Drops Sharply With GPS Tracking</h2>

<p>
  One of the clearest signals in the data is the relationship between GPS tracking and 
  schedule adherence. Vehicles on routes where operators actively monitor live positions 
  show meaningfully lower variance in arrival times at key stages compared to untracked 
  routes operating on the same corridors.
</p>

<p>
  The mechanism isn't complicated: when operators can see that a vehicle is running late, 
  they can act — reassigning a nearby vehicle, alerting waiting passengers, or adjusting 
  dispatch timing from the terminus. Visibility creates accountability, and accountability 
  narrows variance.
</p>

<h2>Finding 4: Idle Time at Terminuses Is Significantly Underestimated</h2>

<p>
  Industry estimates for idle time — the time a vehicle sits stationary at a terminus or 
  stage waiting for a full load — typically run at around 15% of operating hours. Our 
  telemetry data suggests the real figure, for the vehicles we track, is closer to 26%.
</p>

<p>
  The gap between perception and reality matters because idle time is the most addressable 
  inefficiency in the network. Unlike congestion, which operators cannot control, idle time 
  is entirely within the system's influence. Dynamic dispatch — departing on a time schedule 
  rather than a load threshold — is already standard practice in better-optimised transit 
  networks globally. The data suggests Nairobi's network would benefit significantly from 
  the same approach.
</p>

<h2>What the Data Points Toward</h2>

<p>
  None of these findings require exotic interventions. They point toward a single underlying 
  need: operators making decisions with real information rather than intuition.
</p>

<p>
  The matatu network is already efficient by the standards of informal transit globally. With 
  better data, it could be efficient by any standard. That's the work we're doing — and the 
  numbers suggest the upside is substantial.
</p>

